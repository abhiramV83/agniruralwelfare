/**
 * Returns a festival theme by its unique identifier.
 */
export function getFestivalThemeById(id) {
  if (!id) return INDIAN_FESTIVAL_THEMES[0];
  const cleanId = String(id).toLowerCase().trim();
  return (
    INDIAN_FESTIVAL_THEMES.find(
      (f) => f.id === cleanId || f.name.toLowerCase() === cleanId
    ) || null
  );
}

/**
 * Filters festival themes by category or search term
 */
export function filterFestivalThemes(category = "All", search = "") {
  let list = INDIAN_FESTIVAL_THEMES;
  if (category && category !== "All") {
    list = list.filter((f) => f.category.toLowerCase() === category.toLowerCase());
  }
  if (search && search.trim()) {
    const q = search.trim().toLowerCase();
    list = list.filter(
      (f) =>
        f.name.toLowerCase().includes(q) ||
        f.greeting.toLowerCase().includes(q) ||
        f.category.toLowerCase().includes(q)
    );
  }
  return list;
}

