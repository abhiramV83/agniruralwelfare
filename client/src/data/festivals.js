/**
 * Helper to fetch a festival by its ID
 */
export function getFestivalById(id) {
  return FESTIVAL_COLLECTION.find((f) => f.id === id) || null;
}

/**
 * Filter festivals by category and search keyword
 */
export function filterFestivals({ category = "all", searchQuery = "" } = {}) {
  const q = searchQuery.toLowerCase().trim();

  return FESTIVAL_COLLECTION.filter((f) => {
    const matchCategory = category === "all" || f.category.toLowerCase() === category.toLowerCase();
    if (!matchCategory) return false;

    if (!q) return true;

    return (
      f.name.toLowerCase().includes(q) ||
      f.greetingTitle.toLowerCase().includes(q) ||
      f.shortDescription.toLowerCase().includes(q) ||
      f.culturalSignificance.toLowerCase().includes(q) ||
      f.traditionalCelebrations.toLowerCase().includes(q) ||
      f.category.toLowerCase().includes(q)
    );
  });
}

/**
 * Get count of festivals in each category
 */
export function getCategoryCounts() {
  const counts = { all: FESTIVAL_COLLECTION.length };
  FESTIVAL_COLLECTION.forEach((f) => {
    counts[f.category] = (counts[f.category] || 0) + 1;
  });
  return counts;
}

